function resultAdvice(result) {
  const rows = result.gaps.map((gap, position) => {
    const meaning = Math.abs(gap) < 10 ? '实际与理想接近，可保持当前投入。' :
      gap > 0 ? '希望增加这种行为；差距并不表示能力不足。' :
      '希望减少这种行为；可为它设定时间上限，把精力转给优先方向。';
    return {
      position, gap, meaning,
      context: dimensionAdvice[position][result.actual[position] >= 60 ? 1 : 0],
      action: Math.abs(gap) < 10 ? '两周后记录一次实际投入，检查当前节奏是否仍适合自己。' :
        gap > 0 ? dimensionAdvice[position][2] : '下周记录此类任务用时，减少一个非必要环节，两周后检查代价。',
    };
  });
  const tensions = [];
  if (result.ideal[1] >= 75 && result.ideal[4] >= 75) tensions.push('追踪前沿与长期深耕会争夺时间。可设固定阅读窗口，保留主线研究时间。');
  if (result.ideal[3] >= 75 && result.ideal[7] >= 75) tensions.push('高风险探索未必能快速反馈。将探索任务与短周期交付任务分开安排。');
  if (result.actual[6] >= 75 && result.actual[7] < 50) tensions.push('竞争动力高于当前迭代节奏，先检查任务拆分、资源瓶颈和实验反馈周期。');
  if (result.actual[10] >= 75 && result.actual[0] < 50) tensions.push('把批判观察进一步改写成研究问题，并提出一项可检验的建设性方案。');
  return { rows, tensions };
}
