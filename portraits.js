function portraitMarkup(id, mode = 'actual', uncertain = false) {
  const portrait = personaPortraits[id];
  const code = 'P' + String(id + 1).padStart(2, '0');
  return '<div class="portrait-art"><img src="assets/personas/' + code + '.svg" alt="' + names[id] +
    '的专属人物卡通插画" width="480" height="360"><span class="portrait-code">' + code + ' / ' + en[id] + '</span></div>' +
    '<div class="portrait-story"><blockquote>「' + portrait.motto + '」</blockquote>' +
    (mode === 'ideal' ? '<p class="portrait-context">' + (uncertain ?
      '先把这个角色当作一面试衣镜，而不是确定的理想标签。看看哪些部分吸引你，哪些其实不想投入。' :
      '你向往的，是下面这种研究状态。它描述你想靠近的方式，不代表你现在已经如此。') + '</p>' : '') +
    '<p>' + (mode === 'actual' ? portrait.story : portrait.story.replace(/^你是/, '这个角色是')) + '</p>' +
    '<div class="portrait-scene"><h4>有没有一点像你？</h4><p>' + portrait.scene + '</p></div>' +
    '<h4>你带给研究的东西</h4><p>' + portrait.gift + '</p>' +
    '<h4>给这个角色的小提醒</h4><p>' + portrait.trap + '</p>' +
    '<div class="portrait-chapters">' + portraitChapters[id].map(([title, body], position) =>
      '<section class="portrait-chapter"><span class="chapter-number">0' + (position + 1) +
      '</span><h4>' + title + '</h4><p>' + body + '</p></section>').join('') +
    '</div><p class="portrait-footnote">把这份解读当作一面镜子：有共鸣的部分值得留意，不贴合的部分也可以保留自己的判断。它描述研究风格，不替你定义全部的自己。</p></div>';
}
